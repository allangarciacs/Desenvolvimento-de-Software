    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        // TODO add your handling code here:
        Funcionario f = new Funcionario();

        if (txtNome.getText().isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "'Nome' nao pode ficar vazio!",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            f.setNome(txtNome.getText());
        }

        if (txtIdade.getText().isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "'Idade' nao pode ficar vazio!",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            f.setIdade(Integer.parseInt(txtIdade.getText()));
        }

        if (rbtnGeneroMasc.isSelected()) {
            f.setGenero("Masculino");
        } else if (rbtnGeneroFem.isSelected()) {
            f.setGenero("Feminino");
        } else if (rbtnGeneroOutro.isSelected()) {
            f.setGenero("Outro");
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Genero nao selecionado",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        f.setCargo(cmbCargo.getSelectedItem().toString());

        if (txtSalario.getText().isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "'Salario' nao pode ficar vazio!",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            f.setSalario(Double.parseDouble(txtSalario.getText()));
        }

        FuncionarioDAO fDAO = new FuncionarioDAO();

        if (fDAO.inserir(f)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Funcionario cadastrado no BD",
                    "Cadastro",
                    JOptionPane.INFORMATION_MESSAGE
            );
            limparFormulario();
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao cadastrar funcionario no BD",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnInserirActionPerformed

