    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        Pessoa p = new Pessoa();
        p.setId(Integer.parseInt(txtId.getText()));
        p.setNome(txtNome.getText());
        p.setIdioma(cmbIdioma.getSelectedItem().toString());
        
        if(rdoMasculino.isSelected()) {
            p.setSexo("M");
        } else if (rdoFeminino.isSelected()) {
            p.setSexo("F");
        } else {
            System.out.println("Sexo nao selecionado!");
            return;
        }
        
        PessoaDAO pDAO = new PessoaDAO();
        pDAO.editar(p);
        limparFormulario();
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnConsularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsularActionPerformed
        int id = Integer.parseInt(txtId.getText());

        PessoaDAO dao = new PessoaDAO();
        Pessoa pessoa = dao.consultar(id);

        if (pessoa != null) {
            txtResID.setText(""+pessoa.getId());
            txtNome.setText(pessoa.getNome());
            
            if (pessoa.getSexo().equals("M")) {
                rdoMasculino.setSelected(true);
            } else if (pessoa.getSexo().equals("F")) {
                rdoFeminino.setSelected(true);
            }
          
        cmbIdioma.setSelectedItem(pessoa.getIdioma());
            
        } else {
            JOptionPane.showMessageDialog(this, "Nao ha pessoa cadastrada nesse ID!");
        }
    }//GEN-LAST:event_btnConsularActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int id = Integer.parseInt(txtId.getText());
        
        int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir esta pessoa?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
            );
        
        if (resposta == JOptionPane.YES_OPTION) {
            PessoaDAO pessoaDAO = new PessoaDAO();
            pessoaDAO.excluir(id);
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

