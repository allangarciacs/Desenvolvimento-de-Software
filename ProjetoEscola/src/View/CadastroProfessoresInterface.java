    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        Professores p = new Professores();
        p.setNome(txtNome.getText());
        p.setIdade(Integer.parseInt(cmbIdade.getSelectedItem().toString()));
        p.setDisciplina(txtDisciplina.getText());

        professoresDAO pDAO = new professoresDAO();

        if (pDAO.inserir(p)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Professor cadastrado no BD",
                    "Cadastro",
                    JOptionPane.INFORMATION_MESSAGE
            );
            limparFormulario();
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao cadastrar professor no BD",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

