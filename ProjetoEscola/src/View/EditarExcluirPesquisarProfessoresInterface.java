    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um ID!");
            return;
        }

        int idProfessor = Integer.parseInt(txtId.getText());
        professoresDAO pDAO = new professoresDAO();
        Professores p = pDAO.getProfessor(idProfessor);

        if (p == null) {
            txtNome.setText("");
            txtDisciplina.setText("");
            cmbIdade.setSelectedItem(-1);
            JOptionPane.showMessageDialog(this, "Professor nao encotrado!");
        } else {
            txtNome.setText(p.getNome());
            txtDisciplina.setText(p.getDisciplina());
            cmbIdade.setSelectedItem(String.valueOf(p.getIdade()));
        }
    }//GEN-LAST:event_btnPesquisarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
        Professores p = new Professores();
        p.setId(Integer.parseInt(txtId.getText()));
        p.setNome(txtNome.getText());
        p.setIdade(Integer.parseInt(cmbIdade.getSelectedItem().toString()));
        p.setDisciplina(txtDisciplina.getText());

        professoresDAO pDAO = new professoresDAO();
        pDAO.editar(p);
        limparFormulario();
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int resposta = JOptionPane.showConfirmDialog(
                null,
                "Deseja excluir?",
                "Exclusao",
                JOptionPane.YES_NO_OPTION
        );
        if (resposta == JOptionPane.YES_OPTION) {
            professoresDAO pDAO = new professoresDAO();
            pDAO.excluir(Integer.parseInt(txtId.getText()));
            limparFormulario();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

